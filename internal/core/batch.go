package core

import (
	"errors"
	"strings"
)

// ExportBatch renders a Windows .bat that maps every active drive of a device,
// equivalent to what the original web tool generated. The password is written
// in plain text (the same as the original), so the UI warns about that.
func ExportBatch(d Device, password string) (string, error) {
	if strings.ContainsAny(password, "\"\r\n") {
		return "", errors.New("a password containing a double quote or line break cannot be written to a .bat file; use the app's Mount button instead")
	}
	if HasErrors(Validate(d, nil, password != "")) {
		return "", errors.New("fix the highlighted problems before exporting")
	}
	drives := ActiveDrives(d)

	var b []string
	pause := func() {
		if !d.NoPauses {
			b = append(b, "pause")
		}
	}
	b = append(b, "@echo off")
	b = append(b, "rem Generated by SSHFS Station for: "+oneLine(d.Name))
	b = append(b, "")
	b = append(b, "echo Make sure you have installed WinFsp and SSHFS-Win and your device is on and connected to the network ...")
	pause()
	b = append(b, "")
	b = append(b, `set "user=`+trim(d.Username)+`"`)
	b = append(b, `set "pass=`+strings.ReplaceAll(password, "%", "%%")+`"`)
	b = append(b, `set "machine=`+trim(d.Host)+`"`)
	b = append(b, "")
	b = append(b, "echo Deleting existing drives ...")
	for _, dr := range drives {
		b = append(b, "net use "+dr.Letter+": /delete /y")
	}
	pause()
	b = append(b, "")
	b = append(b, "echo Setting your connections now ...")
	for _, dr := range drives {
		rp, err := RemotePath(d, dr)
		if err != nil {
			return "", err
		}
		unc := `\\sshfs.r\%user%@%machine%`
		if p := d.EffectivePort(); p != 22 {
			unc += "!" + itoa(p)
		}
		if rp != "/" {
			unc += strings.ReplaceAll(strings.ReplaceAll(rp, "%", "%%"), "/", `\`)
		}
		b = append(b, "echo Setting "+dr.Letter+": as "+LocationLabel(dr.Location))
		b = append(b, "net use "+dr.Letter+`: "`+unc+`" /user:%user% "%pass%" /persistent:Yes`)
	}
	pause()
	return strings.Join(b, "\r\n") + "\r\n", nil
}

func oneLine(s string) string {
	return strings.NewReplacer("\r", " ", "\n", " ").Replace(trim(s))
}
